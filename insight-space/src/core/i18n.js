const dict = { zh, en };

export function t(key, vars) {
  const current = document.documentElement.dataset.lang === 'en' ? 'en' : 'zh';
  let text = dict[current][key] ?? dict.zh[key] ?? key;
  if (vars && typeof text === 'string') {
    text = text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] == null ? match : String(vars[name])));
  }
  return text;
}

/** 依据当前语言选择对象里的 Zh / En 字段 */
export function tl(zhText, enText) {
  const current = document.documentElement.dataset.lang === 'en' ? 'en' : 'zh';
  return current === 'en' ? (enText || zhText) : (zhText || enText);
}

export function currentLang() {
  return document.documentElement.dataset.lang === 'en' ? 'en' : 'zh';
}
